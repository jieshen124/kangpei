function flowSteps(stage) {
  const st = STAGE_STEPS[String(stage)];
  if (!st) return null;
  const pre = st.pre || [];
  const order = [
    FLOW_SHARED.safe,
    ...pre,
    st.warm || FLOW_SHARED.warm,
    ...st.steps,
    st.cool || FLOW_SHARED.cool,
    FLOW_SHARED.scale,
  ];
  const last = order.length - 1;
  return order.map((s, i) => {
    // 阶段按位置推导：
    // 首步 = 准备；st.pre 里的"病种专项判断"也归到准备（不能算成热身）；
    // 紧随其后的才是热身；末步 = 记录；倒数第二 = 放松；其余 = 核心。
    let derived;
    if (i === 0) derived = 0;
    else if (i <= pre.length) derived = 0;
    else if (i === pre.length + 1) derived = 1;
    else if (i === last) derived = 4;
    else if (i === last - 1) derived = 3;
    else derived = 2;
    const phase = (s.phase != null) ? s.phase : derived;
    return {
      key: s.key, phase, phaseLabel: PHASES[phase],
      title: s.title, goal: s.goal, minutes: s.minutes,
      cues: s.cues || [], donts: s.donts || [], stops: s.stops || [],
    };
  });
}

